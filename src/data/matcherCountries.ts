export function filterMatcherCountries(query: string, limit = 8): MatcherCountry[] {
  const q = query.trim().toLowerCase();
  if (!q) return MATCHER_COUNTRIES.slice(0, limit);
  const starts: MatcherCountry[] = [];
  const includes: MatcherCountry[] = [];
  for (const c of MATCHER_COUNTRIES) {
    const name = c.name.toLowerCase();
    if (name.startsWith(q) || c.code.toLowerCase() === q) starts.push(c);
    else if (name.includes(q)) includes.push(c);
  }
  return [...starts, ...includes].slice(0, limit);
}
